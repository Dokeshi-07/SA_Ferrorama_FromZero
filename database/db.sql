CREATE DATABASE IF NOT EXISTS ferroramaDB; USE
    ferroramaDB;
CREATE TABLE IF NOT EXISTS users(
    id INT AUTO_INCREMENT PRIMARY KEY,
    userName VARCHAR(200) NOT NULL,
    userEmail VARCHAR(200) NOT NULL,
    userPhone VARCHAR(20) NOT NULL,
    userPassword VARCHAR(255) NOT NULL,
    adm BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS routes(
    id INT AUTO_INCREMENT PRIMARY KEY,
    routeName VARCHAR(200) NOT NULL UNIQUE,
    routeState VARCHAR(50) NOT NULL,
    routeLocal VARCHAR(200) NOT NULL
);
CREATE TABLE IF NOT EXISTS train (
    id INT AUTO_INCREMENT PRIMARY KEY,
    trainName VARCHAR(200) NOT NULL,
    trainType VARCHAR(200) NOT NULL,
    cargo VARCHAR(50) NOT NULL,
    trainState VARCHAR(15) NOT NULL,
    routeName VARCHAR(200) NOT NULL,
    FOREIGN KEY (routeName)
        REFERENCES routes(routeName)
        ON DELETE CASCADE
);